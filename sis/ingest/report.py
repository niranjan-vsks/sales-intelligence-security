"""docs/INGEST_REPORT_<file_id>.md: the throughput numbers DESIGN.md section 8 cites."""

import json
import os
import platform
import sys
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from sis.ingest.run import IngestResult


def ram_gb() -> float | None:
    """Physical memory in GB, or None when the platform will not say."""
    try:
        if sys.platform == "win32":
            import ctypes

            class MemStatus(ctypes.Structure):
                _fields_ = [
                    ("length", ctypes.c_ulong), ("load", ctypes.c_ulong),
                    ("total_phys", ctypes.c_ulonglong), ("avail_phys", ctypes.c_ulonglong),
                    ("total_page", ctypes.c_ulonglong), ("avail_page", ctypes.c_ulonglong),
                    ("total_virtual", ctypes.c_ulonglong), ("avail_virtual", ctypes.c_ulonglong),
                    ("avail_ext", ctypes.c_ulonglong),
                ]

            st = MemStatus()
            st.length = ctypes.sizeof(MemStatus)
            ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(st))
            return float(round(st.total_phys / 1024**3, 1))
        return float(round(os.sysconf("SC_PAGE_SIZE") * os.sysconf("SC_PHYS_PAGES") / 1024**3, 1))
    except (OSError, ValueError, AttributeError):
        return None


def write_report(r: "IngestResult", path: Path) -> None:
    wall = r.wall_seconds or float("nan")
    ram = ram_gb()
    lines = [
        f"# Ingest report {r.file_id}",
        "",
        f"Generated by `sis ingest` (pipeline_version {r.pipeline_version}). "
        f"Status: **{r.status}**.",
        "",
        "| Measure | Value |",
        "|---|---|",
        f"| original name | {r.original_name} |",
        f"| byte length (compressed) | {r.byte_length:,} |",
        f"| lines read | {r.lines_read:,} |",
        f"| rows written (banners) | {r.rows_written:,} |",
        f"| rows dropped | {r.rows_dropped:,} |",
        f"| dropped by reason | `{json.dumps(r.dropped_reasons, sort_keys=True)}` |",
        f"| vuln rows written | {r.vuln_rows_written:,} |",
        f"| wall seconds | {r.wall_seconds:,.1f} |",
        f"| lines per second | {r.lines_read / wall:,.0f} |",
        f"| compressed MB per second | {r.byte_length / 1e6 / wall:,.1f} |",
        f"| parquet bytes out, banners | {r.parquet_bytes_banners:,} |",
        f"| parquet bytes out, vulns | {r.parquet_bytes_vulns:,} |",
        f"| workers | {r.workers} |",
        f"| machine | {os.cpu_count()} logical CPUs, "
        f"{ram if ram is not None else 'RAM not measured'} GB RAM, {platform.platform()} |",
        "",
        "Lines read = rows written + rows dropped; the run fails otherwise.",
        "",
        "## New provider fields",
        "",
    ]
    if r.new_keys:
        lines += [f"- `{k}`: {n:,} records" for k, n in r.new_keys.items()]
        lines += ["", "Unknown top-level blocks are kept in `extra_json`; promote them in a later "
                  "pipeline version."]
    else:
        lines.append("None: every top-level key was in `config/known_top_keys.txt`.")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
